"""Write the inventory skeleton for a snapshot (PLAN.md §5 step 3).

Lists every canonical image and scroll stitch per app, and the apps the web
research says exist (research/facts.md) that have no captures, so they can go
into MISSING.md. The home-screen order and the tap map ("which tap leads
where") are filled in by looking at the canonical images; this script leaves
marked TODO lines for them rather than guessing.

  python tools/inventory.py <snapshot-id>
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from common import CONTENT, REFERENCE, ROOT

FACTS = ROOT / "research" / "facts.md"


def research_apps(facts: Path = FACTS) -> list[str]:
    """Accepted app names from the facts table (first column, status 'accepted')."""
    apps = []
    for line in facts.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 6 and cells[-1].startswith("accepted"):
            name = re.sub(r"\s*\(.*?\)", "", cells[0]).strip()
            if name and not name.startswith("App"):
                apps.append(name)
    return apps


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def build(snapshot: str) -> str:
    ref = REFERENCE / snapshot
    canon = CONTENT / snapshot / "canonical"
    captured = sorted(p.name for p in ref.iterdir() if p.is_dir()) if ref.is_dir() else []
    lines = [f"# Inventory: {snapshot}", "",
             "Generated by tools/inventory.py. Fill in the TODO lines by looking at the canonical images.", "",
             "## Home-screen order", "", "TODO: list the apps exactly as the home screen shows them, left to right, top to bottom.", "",
             "## Apps and screens", ""]
    for app in captured:
        shots = sorted((canon / app).glob("*.png")) if (canon / app).is_dir() else []
        scrolls = sorted((ref / app / "scroll").glob("*.mp4")) if (ref / app / "scroll").is_dir() else []
        trans = sorted((ref / app / "transitions").glob("*.mp4")) if (ref / app / "transitions").is_dir() else []
        lines.append(f"### {app}")
        lines.append(f"- canonical screens: {len(shots)}")
        for s in shots:
            lines.append(f"  - {s.name}: TODO taps -> ")
        lines.append(f"- scroll videos: {len(scrolls)}; transition videos: {len(trans)}")
        lines.append("")
    lines += ["## Web research vs captures", ""]
    have = {norm(a) for a in captured}
    for app in research_apps():
        status = "captured" if norm(app) in have else "NOT CAPTURED -> MISSING.md"
        lines.append(f"- {app}: {status}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("snapshot")
    a = ap.parse_args(argv)
    out = CONTENT / a.snapshot / "inventory.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(a.snapshot), encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
